DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_tables WHERE schemaname = current_schema() AND tablename = 'galette_eeds_structures') THEN
    CREATE TABLE galette_eeds_structures (
      id_structure integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      parent_structure integer DEFAULT NULL REFERENCES galette_eeds_structures(id_structure) ON DELETE RESTRICT ON UPDATE CASCADE,
      structure_type varchar(50) NOT NULL,
      structure_code varchar(100) NOT NULL UNIQUE,
      structure_name varchar(255) NOT NULL,
      recognition_status varchar(50) NOT NULL DEFAULT 'pending',
      effective_start date NOT NULL,
      effective_end date DEFAULT NULL,
      created_at timestamp NOT NULL,
      created_by integer DEFAULT NULL REFERENCES galette_adherents(id_adh) ON DELETE RESTRICT ON UPDATE CASCADE
    );
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_tables WHERE schemaname = current_schema() AND tablename = 'galette_eeds_member_scopes') THEN
    CREATE TABLE galette_eeds_member_scopes (
      id_scope integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      id_adh integer NOT NULL REFERENCES galette_adherents(id_adh) ON DELETE RESTRICT ON UPDATE CASCADE,
      id_structure integer NOT NULL REFERENCES galette_eeds_structures(id_structure) ON DELETE RESTRICT ON UPDATE CASCADE,
      scope_permission varchar(100) NOT NULL,
      effective_start date NOT NULL,
      effective_end date DEFAULT NULL,
      created_at timestamp NOT NULL,
      created_by integer DEFAULT NULL REFERENCES galette_adherents(id_adh) ON DELETE RESTRICT ON UPDATE CASCADE
    );
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS galette_eeds_member_scopes_member ON galette_eeds_member_scopes(id_adh);
CREATE INDEX IF NOT EXISTS galette_eeds_member_scopes_structure ON galette_eeds_member_scopes(id_structure);

DO $$
BEGIN
